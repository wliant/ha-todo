package com.hatodo.calendar;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import java.time.Instant;
import java.time.LocalDate;
import java.util.UUID;

/**
 * One occurrence of one event, as a feed last reported it.
 *
 * <p>Not an aggregate anybody edits: the poller is the only writer, and it
 * replaces a feed's rows wholesale rather than reconciling them. An event that
 * moved, an event that was edited and an event that was deleted are all just a
 * different set of rows next time, which is the simplification the whole
 * feature rests on - there is no identity to preserve across a refresh, so
 * there is no diffing, no tombstones and nothing subtle to get wrong.
 *
 * <p>A recurring series arrives here already expanded, one row per occurrence
 * inside the cached window.
 *
 * <p><b>All-day is structural, not a formatting choice.</b> An all-day event
 * carries a {@link LocalDate} and no instant, because resolving a bare
 * {@code DTSTART;VALUE=DATE} to an instant has to choose a midnight to resolve
 * it against and that choice is wrong in every zone but one. See adr/0036.
 */
@Entity
@Table(name = "calendar_event")
public class CalendarEvent {

    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    private UUID id;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "feed_id", nullable = false)
    private CalendarFeed feed;

    /** RFC 5545 UID: how one appointment seen through two feeds is recognised. */
    @Column(nullable = false)
    private String uid;

    @Column(nullable = false)
    private String summary;

    @Column
    private String description;

    @Column
    private String location;

    @Column(name = "all_day", nullable = false)
    private boolean allDay;

    @Column(name = "starts_at")
    private Instant startsAt;

    @Column(name = "ends_at")
    private Instant endsAt;

    @Column(name = "start_date")
    private LocalDate startDate;

    /** Exclusive, as DTEND is. */
    @Column(name = "end_date")
    private LocalDate endDate;

    /**
     * The household-zone day this occurrence is placed on.
     *
     * <p>Maintained here rather than generated by Postgres: the derivation
     * needs {@code AT TIME ZONE}, which is STABLE rather than IMMUTABLE and so
     * refused in a generation expression - and a zone baked into the schema
     * could not be reconfigured anyway.
     */
    @Column(name = "occurs_on", nullable = false)
    private LocalDate occursOn;

    /** -1 for an all-day event, so it sorts above every timed one on its day. */
    @Column(name = "sort_minute", nullable = false)
    private short sortMinute;

    protected CalendarEvent() {
        // for JPA
    }

    public CalendarEvent(CalendarFeed feed, ParsedEvent parsed) {
        this.feed = feed;
        this.uid = parsed.uid();
        this.summary = parsed.summary();
        this.description = parsed.description();
        this.location = parsed.location();
        this.allDay = parsed.allDay();
        this.startsAt = parsed.startsAt();
        this.endsAt = parsed.endsAt();
        this.startDate = parsed.startDate();
        this.endDate = parsed.endDate();
        this.occursOn = parsed.occursOn();
        this.sortMinute = parsed.sortMinute();
    }

    public UUID getId() {
        return id;
    }

    public CalendarFeed getFeed() {
        return feed;
    }

    public String getUid() {
        return uid;
    }

    public String getSummary() {
        return summary;
    }

    public String getDescription() {
        return description;
    }

    public String getLocation() {
        return location;
    }

    public boolean isAllDay() {
        return allDay;
    }

    public Instant getStartsAt() {
        return startsAt;
    }

    public Instant getEndsAt() {
        return endsAt;
    }

    public LocalDate getStartDate() {
        return startDate;
    }

    public LocalDate getEndDate() {
        return endDate;
    }

    public LocalDate getOccursOn() {
        return occursOn;
    }

    public short getSortMinute() {
        return sortMinute;
    }
}
